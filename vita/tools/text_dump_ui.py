#!/usr/bin/env python3
"""
Lists the game's other texts for translating (vita/translation/README.md):

  python3 vita/tools/text_dump_ui.py [OUT]

assets1C (menus, the start screens, multiplayer, credits: NUL-separated strings, drawn
through func_15042D94/func_15042ECC; the key is the CRC32 of the whole string) and assets1A
(the hint book's pages, shown in speech bubbles: keyed per page as text_dump.py does).
Writes OUT (default vita/translation/en_reference_ui.txt; ROM-derived, not committed).
"""
import os
import sys
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import text_dump as T

ROOT = T.ROOT
RZIP = os.path.join(ROOT, "conker", "assets", "rzip")


def is_ui(s):
    letters = sum(0x41 <= c <= 0x5A or 0x61 <= c <= 0x7A for c in s)
    ok = all(c == 0x0A or 0x20 <= c <= 0x7E or c >= 0xA1 for c in s)
    return ok and letters >= 2


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "vita", "translation", "en_reference_ui.txt")
    seen = set()
    lines = ["# Conker's menus and hints (assets1C strings, assets1A pages). Generated by",
             "# vita/tools/text_dump_ui.py; ROM-derived, don't commit."]
    data = open(os.path.join(RZIP, "assets1C", "0000"), "rb").read()
    lines.append("\n# assets1C/0000")
    for b in [data] + list(T.blocks(data)):
        for s in b.split(b"\0"):
            if len(s) < 2 or not is_ui(s):
                continue
            key = zlib.crc32(s) & 0xFFFFFFFF
            if key in seen:
                continue
            seen.add(key)
            lines.append("%08x = %s" % (key, T.notation(s)))
    data = open(os.path.join(RZIP, "assets1A", "0000"), "rb").read()  # English
    lines.append("\n# assets1A/0000")
    for b in [data] + list(T.blocks(data)):
        for s in b.split(b"\0"):
            if len(s) < 3 or not is_ui(s):
                continue
            for page in s.split(bytes([T.PAGE_BREAK])):
                if not page.strip():
                    continue
                key = zlib.crc32(page) & 0xFFFFFFFF
                if key in seen:
                    continue
                seen.add(key)
                lines.append("%08x = %s" % (key, T.notation(page)))
    open(out_path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("%d texts -> %s" % (len(seen), out_path))


if __name__ == "__main__":
    main()
