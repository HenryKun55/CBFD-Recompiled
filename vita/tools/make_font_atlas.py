#!/usr/bin/env python3
"""Renders ASCII 32..126 from a TTF into an 8-bit alpha atlas for the Vita build's menu
(vita/src/font_atlas.h). Cell 127 is solid, for drawing filled rectangles.
usage: make_font_atlas.py font.ttf out.h"""
import sys
from PIL import Image, ImageDraw, ImageFont

font_path, out_path = sys.argv[1], sys.argv[2]
SIZE = 26
CELL_W, CELL_H = 28, 34
COLS = 16
font = ImageFont.truetype(font_path, SIZE)
try:
    font.set_variation_by_name('SemiBold')
except Exception:
    pass
chars = list(range(32, 128))
rows = (len(chars) + COLS - 1) // COLS
W, H = COLS * CELL_W, rows * CELL_H
atlas = Image.new('L', (W, H), 0)
draw = ImageDraw.Draw(atlas)
advances = []
ascent, descent = font.getmetrics()
for i, c in enumerate(chars):
    x, y = (i % COLS) * CELL_W, (i // COLS) * CELL_H
    if c == 127:
        draw.rectangle([x + 2, y + 2, x + CELL_W - 3, y + CELL_H - 3], fill=255)
        advances.append(CELL_W)
        continue
    ch = chr(c)
    draw.text((x + 2, y + 2), ch, font=font, fill=255)
    advances.append(int(round(font.getlength(ch))) + 1)
with open(out_path, 'w') as f:
    f.write('// Generated by vita/tools/make_font_atlas.py from Inter (SIL Open Font License).\n')
    f.write('#pragma once\n#include <cstdint>\n')
    f.write(f'constexpr int font_atlas_width = {W}, font_atlas_height = {H};\n')
    f.write(f'constexpr int font_cell_w = {CELL_W}, font_cell_h = {CELL_H}, font_cols = {COLS};\n')
    f.write('constexpr uint8_t font_advance[96] = {' + ','.join(map(str, advances)) + '};\n')
    data = atlas.tobytes()
    f.write('constexpr uint8_t font_atlas[%d] = {\n' % len(data))
    for i in range(0, len(data), 32):
        f.write(','.join(str(b) for b in data[i:i + 32]) + ',\n')
    f.write('};\n')
print(W, H, len(advances))
