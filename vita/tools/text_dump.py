#!/usr/bin/env python3
"""
Lists the game's speech-bubble pages for translating (vita/translation/README.md):

  python3 vita/tools/text_dump.py [OUT]

Reads the cutscene scripts the decompilation's extract unpacked
(conker/assets/rzip/assets06), whose text is deflated inside them, and writes OUT
(default vita/translation/en_reference.txt, ROM-derived: not committed): one line per
page, "<key> = <text>", in the same notation as the translation files. The key is the
CRC32 of the page's bytes, as host/src/text_translation.cpp computes it in the game.
"""
import os
import struct
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ASSETS = os.path.join(ROOT, "conker", "assets", "rzip", "assets06")
PAGE_BREAK = 0xBD


def entries(d):
    """The table at the start of a script file or block: (offset, size, deflated)."""
    if len(d) < 16:
        return None
    first = struct.unpack(">I", d[:4])[0]
    if first == 0 or first % 8 or first > len(d) or first > 0x4000:
        return None
    out = []
    for i in range(first // 8):
        off, size = struct.unpack(">II", d[i * 8:i * 8 + 8])
        deflated = (size >> 28) & 1
        size &= 0x0FFFFFFF
        if off + size > len(d):
            return None
        out.append((off, size, deflated))
    return out


def blocks(d, depth=0):
    """Every block of a script file, deflated ones unpacked, nested tables walked."""
    t = entries(d) if depth < 4 else None
    for off, size, deflated in t or []:
        if not size:
            continue
        b = d[off:off + size]
        if deflated:
            try:
                b = zlib.decompress(b[4:], -15)
            except zlib.error:
                continue
            yield b
        yield from blocks(b, depth + 1)


# The accented letters the game's font has (D_80085930).
FONT_ACCENTS = set("ÄäÖöÜüßÀàÂâÇçÉéÈèÊêËëÎîÏïÔôÛûÙùú".encode("latin-1"))


def is_text(s):
    letters = sum(c >= 0x61 and c <= 0x7A for c in s)
    # The dialogue is written in lowercase (drawn in capitals): capitals are other data.
    ok = all(c == 0x0A or 0x20 <= c <= 0x7E or 0xA1 <= c <= 0xBF or c in FONT_ACCENTS for c in s)
    ok = ok and not any(0x41 <= c <= 0x5A or c == 0x40 for c in s)
    return ok and letters >= 2 and letters * 2 >= len([c for c in s if c < 0x80])


def notation(page):
    """Bytes to the translation files' text: \\n for a new line, <XX> for a control code."""
    out = []
    for c in page:
        if c == 0x0A:
            out.append("\\n")
        elif 0xA1 <= c <= 0xBF:
            out.append("<%02X>" % c)
        elif c >= 0xC0:
            out.append(bytes([c]).decode("latin-1"))
        else:
            out.append(chr(c))
    return "".join(out)


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "vita", "translation", "en_reference.txt")
    seen = {}
    order = []
    for name in sorted(n for n in os.listdir(ASSETS) if n.isdigit()):
        data = open(os.path.join(ASSETS, name), "rb").read()
        for b in blocks(data):
            for s in b.split(b"\0"):
                if len(s) < 3 or not is_text(s):
                    continue
                for page in s.split(bytes([PAGE_BREAK])):
                    if not page.strip():
                        continue
                    key = zlib.crc32(page) & 0xFFFFFFFF
                    if key not in seen:
                        seen[key] = (name, page)
                        order.append(key)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("# Conker's speech-bubble pages (from the cutscene scripts, assets06). Generated by\n"
                "# vita/tools/text_dump.py; ROM-derived, don't commit. Comments name the script file.\n")
        last = None
        for key in order:
            name, page = seen[key]
            if name != last:
                f.write("\n# assets06/%s\n" % name)
                last = name
            f.write("%08x = %s\n" % (key, notation(page)))
    print("%d pages -> %s" % (len(order), out_path))


if __name__ == "__main__":
    main()
